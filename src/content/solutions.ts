// Товары подбираются из каталога по категории и названию, а не списком slug-ов: каталог меняется, страницы — нет.
import type { L } from "@/i18n";
import type { FaqId } from "@/i18n/pages/solutions";
import { products } from "./catalog";
import { solutionImages } from "./solution-images";
import type { Product, Solution, SolutionId } from "./types";

export type SolutionGroup = "curtains" | "window" | "special" | "manual";

const has = (p: Product, re: RegExp) => re.test(`${p.slug} ${p.name} ${p.title.ru}`);
// Трубчатый мотор (45 мм) — для рулонных штор и уличных систем; в раздвижные не идёт.
const isTubular = (p: Product) => has(p, /tub|труб/i);
const isBend = (p: Product) => p.category === "parts" && has(p, /povorot|поворот|bend|curve/i);
const sliding = () => products.filter((p) => p.category === "kits");
// Детали шины (профиль, ремень, бегунки…) — для тех, кто докупает или меняет часть карниза. Повороты — только эркеру.
const trackParts = () => products.filter((p) => p.category === "parts" && !isBend(p));
// В нишу первым — компактный мотор: он почти не виден снизу.
const isCompact = (p: Product) => has(p, /mini|n99/i);
const compactFirst = (list: Product[]) => [...list.filter(isCompact), ...list.filter((p) => !isCompact(p))];

const match: Record<SolutionId, () => Product[]> = {
  pryamye: () => [...sliding(), ...trackParts()],
  "skrytyy-v-nishu": () => [...compactFirst(sliding()), ...trackParts()],
  erker: () => [...sliding(), ...products.filter(isBend), ...trackParts()],
  dvuhryadnye: () => [...sliding(), ...trackParts()],
  rulonnye: () => products.filter((p) => (p.category === "motors" && isTubular(p)) || has(p, /rulon|рулон|roller/i)),
  rimskie: () => products.filter((p) => has(p, /rimsk|римск|roman/i)),
  "zhalyuzi-i-plisse": () => products.filter((p) => has(p, /zhalyuz|жалюз|plisse|плиссе|blind/i)),
  "lift-sistemy": () => products.filter((p) => p.category === "lift"),
  ulichnye: () => products.filter((p) => has(p, /markiz|маркиз|pergol|пергол|zip/i) || (p.category === "motors" && isTubular(p))),
  "obychnye-karnizy": () => products.filter((p) => p.category === "manual"),
};

/** Есть ли в каталоге повороты — только тогда пишем о них на странице эркера. */
