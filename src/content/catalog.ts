// Прайс из Google-таблицы (scripts/prices.mjs → data/prices.snapshot.json) поверх данных каталога.
// Пустая цена в таблице не затирает формулу комплекта; у штучного товара пустая цена — знак сома.
type PriceRow = { price: number | null; perMeter: number | null; stock?: "in" | "order"; leadDays?: string };
const prices = (snapshot as { items: Record<string, PriceRow> }).items;

function withPrice(p: Product): Product {
  const r = prices[p.slug];
  if (!r) return p;
  const price =
    p.kind === "kit"
      ? { ...p.price, base: r.price ?? p.price.base, perMeter: r.perMeter ?? p.price.perMeter }
      : { ...p.price, unit: r.price ?? p.price.unit ?? null };
  return { ...p, price, stock: r.stock ?? p.stock, leadDays: r.leadDays ?? p.leadDays };
}

export const products: Product[] = base.map(withPrice);

export const productBySlug = (slug: string) => products.find((p) => p.slug === slug);
